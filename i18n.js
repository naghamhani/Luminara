const langBtn = document.getElementById('langToggle');
const langBtnMobile = document.getElementById('langToggleMobile');

function setLang(lang){
  const html = document.documentElement;
  const ar = lang === 'ar';
  html.setAttribute('lang', ar ? 'ar' : 'en');
  html.setAttribute('dir', ar ? 'rtl' : 'ltr');
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(ar){
      if(I18N[key] != null){
        if(el.dataset.en == null) el.dataset.en = el.innerHTML;
        el.innerHTML = I18N[key];
      }
    } else if(el.dataset.en != null){
      el.innerHTML = el.dataset.en;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const key = el.getAttribute('data-i18n-placeholder');
    if(ar){
      if(I18N[key] != null){
        if(el.dataset.enPh == null) el.dataset.enPh = el.getAttribute('placeholder') || '';
        el.setAttribute('placeholder', I18N[key]);
      }
    } else if(el.dataset.enPh != null){
      el.setAttribute('placeholder', el.dataset.enPh);
    }
  });
  const label = ar ? 'EN' : 'عربي';
  if (langBtn) langBtn.textContent = label;
  if (langBtnMobile) langBtnMobile.textContent = label;
  try{ localStorage.setItem('lum_lang', lang); }catch(e){}
}

const toggleLang = () => {
  setLang(document.documentElement.getAttribute('dir') === 'rtl' ? 'en' : 'ar');
};
if (langBtn) langBtn.addEventListener('click', toggleLang);
if (langBtnMobile) langBtnMobile.addEventListener('click', toggleLang);

let saved = null;
try{ saved = localStorage.getItem('lum_lang'); }catch(e){}
if(saved === 'ar' || (!saved && (navigator.language||'').toLowerCase().startsWith('ar'))){
  setLang('ar');
}
